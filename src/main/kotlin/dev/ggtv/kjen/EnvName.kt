package dev.ggtv.kjen

/**
 * Правила записи имён переменных окружения в конфиге.
 *
 * Живут отдельно от токенейзеров, потому что правило повторялось в трёх
 * местах — в разборе `.kn`, в разборе `.crn` и в лексере редактора, — и
 * разъезжалось само по себе. Стоило расширить алфавит в одном, как редактор
 * начал подсвечивать половину имени, а второй разбор — иначе. Здесь одно
 * место, где алфавит определён один раз.
 *
 * ## Что считается именем
 *
 * Буква латинского алфавита, цифра, `_` и `-`. Имя обязано начинаться с буквы
 * или `_`: `$1BAD` — это не переменная, а доллар и текст, и остаётся ими.
 * `-` разрешён, потому что поле Env в лаунчерах и переменная в systemd-юните
 * вполне могут называться `BASE-URL`, и требовать переименовывать их ради
 * конфига плаща — значит требовать лишнего.
 *
 * Всё остальное имя обрывает: точка, слэш, двоеточие, запятая, пробел и любой
 * прочий символ. Отсюда `$BASE/api/cape.png` → `localhost:8080/api/cape.png`:
 * `BASE` кончается на слэше, а `/api/cape.png` дописывается как есть. Обрыв
 * на границе символов — единственное правило, при котором не нужно угадывать,
 * где по замыслу автора кончилось имя: точка в версии и слэш в пути оба
 * обрывают одинаково, и специальных случаев не возникает.
 *
 * ## Дефолт
 *
 * Отделяется только `:-`, как в `sh`. Одиночный `-` разделителем быть не
 * может: он же часть имени, и `${A-B}` — это переменная `A-B`. Иначе одна и
 * та же запись означала бы разное в зависимости от того, в скобках она или
 * нет, а это худший вид неоднозначности — тот, что обнаруживается на проде.
 */
object EnvName {

    /** Первый символ имени: буква или `_`. */
    fun isStart(c: Char): Boolean = c in 'A'..'Z' || c in 'a'..'z' || c == '_'

    /** Остальные символы имени: буква, цифра, `_`, `-`. */
    fun isContinue(c: Char): Boolean = isStart(c) || c in '0'..'9' || c == '-'

    /** Имя целиком верно как имя переменной. */
    fun isValid(name: String): Boolean =
        name.isNotEmpty() && isStart(name[0]) && name.drop(1).all(::isContinue)

    /**
     * Длина имени, если [input] с него начинается, иначе `0`.
     *
     * [input] — весь остаток строки от `$`, вместе с хвостом: `$BASE/api`
     * даст `4`. Хвост не обрезается, а остаётся следующему символу обхода.
     */
    fun lengthAt(input: String): Int {
        if (input.isEmpty() || !isStart(input[0])) return 0
        var i = 1
        while (i < input.length && isContinue(input[i])) i += 1
        return i
    }

    /**
     * Разобрать содержимое `${...}`: имя и значение после `:-`.
     *
     * Второй элемент `null`, если `:-` не было. Значение после `:-` — строка
     * целиком, включая двоеточия и дефисы: дефолт это текст, а не выражение,
     * и искать в нём разделители незачем.
     */
    fun splitDefault(expression: String): Pair<String, String?> {
        val separator = expression.indexOf(":-").takeIf { it >= 0 } ?: return expression to null
        return expression.substring(0, separator) to expression.substring(separator + 2)
    }
}
