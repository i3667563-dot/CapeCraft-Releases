package dev.ggtv.capecraft.schema

/**
 * Журнал сервера схемы.
 *
 * ## Почему не slf4j
 *
 * Схема живёт в двух процессах: в LSP (три зависимости, `lspRuntime`) и в
 * моде, где журнал уже есть. Свой объект с принтером — общий знаменатель:
 * в моде подхватится `CapeCraftLog`, в сервере уйдёт в stderr, который и так
 * пишется мимо протокола (`lsp/Main.kt`).
 *
 * ## Почему сюда, а не в `lsp`
 *
 * Разбор дескриптора нужен не только редактору: мод тоже читает дескриптор
 * аддона, чтобы `/cp status` показал, что за типы стоят за `type = "seed"`.
 * Объект в `schema` — то место, где оба процесса сходятся.
 */
object LspLog {

    /**
     * Куда писать. По умолчанию stderr.
     *
     * Подменяется в тестах, чтобы поймать предупреждение о плохом дескрипторе
     * и убедиться, что оно вообще прозвучало: молча проглоченная опечатка в
     * `types` выглядит в редакторе как «аддон ничего не объявил».
     */
    @Volatile
    private var sink: (String) -> Unit = { System.err.println(it) }

    /** Предупреждение: разбираем дальше, но пользователь должен знать. */
    fun warn(message: String) = sink("[capecraft-lsp] $message")

    /** Заметка для журнала: нашлось то, что стоит показать. */
    fun info(message: String) = sink("[capecraft-lsp] $message")

    /** Подмена приёмника для тестов. */
    fun overrideForTest(target: (String) -> Unit) {
        sink = target
    }

    /** Возврат к настоящему stderr. */
    fun reset() {
        sink = { System.err.println(it) }
    }
}