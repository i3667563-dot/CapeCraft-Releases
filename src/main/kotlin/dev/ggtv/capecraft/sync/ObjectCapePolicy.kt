package dev.ggtv.capecraft.sync

import dev.ggtv.capecraft.condition.ProviderSelector
import dev.ggtv.capecraft.provider.Provider
import dev.ggtv.capecraft.schema.Placeholders
import dev.ggtv.koren.WorldContext

/**
 * Какой набор функций носить для объекта, который сейчас на экране.
 *
 * ## Правило
 *
 * 1. **Свой** id — всегда локальный набор, без ожидания: свой конфиг и есть
 *    набор, который ты сам надел.
 * 2. Объект **объявил** набор (роустер отдал его `id` с функциями) — набор
 *    объекта, со его `when` и приоритетами, посчитанный против **его** мира.
 * 3. Объект **объявил пустоту** — набора нет ни у кого, и показывать нечего:
 *    применяем свой локальный, как в п. 4, но сразу. Ждать тут нечего:
 *    объявление уже пришло и сказало «ничего», а не «ещё не дошло».
 * 4. Объект **не объявил** ничего — [ANNOUNCE_GRACE_MS] ждём объявление.
 *    Молчание может означать «ещё не дошло», и тогда 5 секунд — пустой плащ
 *    вместо нормального. Отсутствие объявления означает «синхронизации нет»:
 *    у клиента без мода, с выключенной синхронизацией или на сервере без
 *    CapeCraft объявления не будет никогда, а ждать вечно нельзя. По
 *    истечении срока навязываем **свой** локальный набор — и дальше он
 *    применяется, пока объект сам не объявится.
 *
 * ## Почему пустое объявление — это «не объявил»
 *
 * Клиент без провайдеров честно объявляет пустой список: [announce] шлётся
 * всегда, даже когда набор пуст. Если считать это объявлением, игрок без
 * конфига навсегда остаётся без плаща — а по правилу п. 4 он обязан получить
 * мой набор, потому что его плащ находится тем же запросом по `{username}`.
 * Проверено на живых двух клиентах: GGSHNIKK с web-провайдером и Eonixx без
 * провайдеров. Пустое объявление от Eonixx гасило показ, хотя оба аккаунта
 * были зарегистрированы на одном провайдере.
 *
 * @see dev.ggtv.capecraft.sync.CapeSyncState.onConfigChanged объявление пустого набора
 *
 * ## Почему принудительно, а не «нет плаща»
 *
 * Провайдеры адресуются по `{username}`/`{uuid}`: плащ зарегистрированного у
 * твоего провайдера человека находится тем же запросом, что и любой другой.
 * Отказ показывать его — это не «я никого не знаю», а «я вижу игрока и
 * специально не показываю ему ничего», хотя данные под рукой. Насильная
 * привязка своего набора к такому объекту и есть то, что нужно: не угадывать,
 * а применять своё.
 *
 * ## Почему это не ломает чужие наборы
 *
 * [Decision.DECLARED] проверяется раньше принудительной, и объявление имеет
 * приоритет всегда. Поэтому игрок, который установит мод и переобъявится,
 * получит свой набор, а не мой: срок ожидания нужен только тем, кто не
 * объявляется вовсе.
 *
 * [Decision.SELF] идёт раньше [Decision.DECLARED] намеренно: свой `file`-плащ
 * по умолчанию не раздаётся (`shareLocalProviders = false`), и в собственном
 * роустере его нет. Если бы «свой» брал набор из снимка, игрок потерял бы свой
 * локальный плащ ровно в тот момент, когда мод вошёл на сервер.
 */
object ObjectCapePolicy {

    /**
     * Сколько ждать объявление объекта, прежде чем навязать свой набор, мс.
     *
     * 5 секунд с запасом перекрывают задержку входа: игрок появился на экране
     * раньше, чем его `Announce` дошёл до сервера, а снимок роустера — до нас.
     */
    const val ANNOUNCE_GRACE_MS: Long = 5_000L

    /** Что показывать объекту. */
    enum class Decision {
        /** Свой набор из локального конфига, сразу и без ожидания. */
        SELF,

        /** Набор, объявленный сервером для этого объекта. */
        DECLARED,

        /** Набор не выбран: ждём объявление, срок ещё не вышел. */
        WAIT,

        /** Срок вышел, объявления не будет — навязываем свой набор. */
        FORCED_LOCAL,
    }

    /** Решение вместе с посчитанным порядком провайдеров. */
    data class Resolution(
        val decision: Decision,
        val providers: List<Provider>,
    )

    /**
     * Решение для одного объекта — без раскладки по провайдерам.
     *
     * @param isSelf это мой собственный игрок.
     * @param declared объявил ли объект **непустой** набор (роустер).
     * @param spokeEmpty объявил ли объект пустой набор: объявление пришло, но
     *   сказало «ничего». Отличать от молчания обязательно — см. KDoc.
     * @param firstSeenMs когда объект увиден впервые (монотонные мс).
     * @param nowMs сейчас (монотонные мс).
     * @param context состояние мира **того, кого видно**.
     * @param vars контекст переменных **того, кого видно** — для `if`. Считается
     *   локально у зрителя: `username`/`uuid` известны любому, кто видит игрока,
     *   а `root` и `$*` намеренно свои на каждой машине (как `{root}` в
     *   неразвёрнутом URL-шаблоне, который тоже едет по сети).
     * @param graceMs срок ожидания; 0 — навязать свой набор сразу.
     */
    fun decide(
        isSelf: Boolean,
        declared: Boolean,
        spokeEmpty: Boolean = false,
        firstSeenMs: Long,
        nowMs: Long,
        graceMs: Long = ANNOUNCE_GRACE_MS,
    ): Decision = when {
        // Порядок обязателен: SELF выше DECLARED (см. KDoc про shareLocalProviders),
        // DECLARED выше ожидания (объявление важнее таймера).
        isSelf -> Decision.SELF
        declared -> Decision.DECLARED
        // Пустое объявление важно поставить ДО ожидания: срок ожидания нужен
        // для молчания, а молчанием пустое объявление не является.
        spokeEmpty -> Decision.FORCED_LOCAL
        // Отрицательное ожидание (часы сдвинулись назад) — тоже ждём: навязать
        // свой набор из-за соскочившего таймера нельзя, это не «молчание».
        nowMs - firstSeenMs < graceMs -> Decision.WAIT
        else -> Decision.FORCED_LOCAL
    }

    /**
     * Что именно применять к объекту: решение плюс отобранный порядок.
     *
     * Условия считаются против [context] **того, кого видно**, а не своего
     * мира: объявленный набор принадлежит ему, и «джунглевый» плащ должен
     * показаться только тому, кто стоит в джунглях.
     *
     * @param declaredProviders набор из роустера; `null` — объявления нет.
     *   Пустой список — это объявление, но пустое, и оно трактуется как
     *   отсутствие набора, а не как «показать нечего».
     * @param localProviders мой набор из `capeCraft.providers`.
     */
    fun resolve(
        isSelf: Boolean,
        declaredProviders: List<Provider>?,
        localProviders: List<Provider>,
        firstSeenMs: Long,
        nowMs: Long,
        context: WorldContext,
        vars: Placeholders.Context,
        graceMs: Long = ANNOUNCE_GRACE_MS,
    ): Resolution {
        val decision = decide(
            isSelf = isSelf,
            declared = !declaredProviders.isNullOrEmpty(),
            spokeEmpty = declaredProviders != null && declaredProviders.isEmpty(),
            firstSeenMs = firstSeenMs,
            nowMs = nowMs,
            graceMs = graceMs,
        )
        val selected = when (decision) {
            Decision.SELF, Decision.FORCED_LOCAL -> localProviders
            Decision.DECLARED -> declaredProviders.orEmpty()
            Decision.WAIT -> emptyList()
        }
        return Resolution(decision, ProviderSelector.select(selected, context, vars))
    }
}
