package dev.ggtv.capecraft.sync

/**
 * Константы и жёсткие лимиты протокола CapeCraft Sync v3.
 *
 * Направление ровно обратное v1: клиент **объявляет свой** набор провайдеров,
 * сервер ничего не решает и только рассылает объявления остальным. Сервер —
 * ретранслятор, а не источник истины (см. AGENTS.md, раздел «Sync v2»).
 *
 * Все лимиты зафиксированы здесь, чтобы клиент и сервер проверяли их одинаково,
 * а разбор входящих байтов не мог выделить гигабайт памяти на злонамеренном
 * (или сломанном) сервере.
 */
object SyncProtocol {
    /**
     * Версия протокола. Несовместимые изменения — только с бампом этого числа.
     *
     * v2 несовместим с v1 полностью: в v1 клиент слал только `requestId` и
     * получал провайдеры **сервера**, в v2 клиент шлёт свои. Формат сообщений
     * тоже другой, поэтому версия гейтится первым байтом, а не «на глаз».
     *
     * v3 добавляет условие `if` (переменные вместо полей мира) в объявление
     * провайдера. Формат не менялся, а **добавилось необязательное поле** —
     * тем не менее версия поднята, а не оставлена v2: старый клиент прочитал бы
     * запись провайдера посимвольно и сдвинул весь поток, потому что длины
     * не сериализованы, а количество полей фиксировано. Ставить на совместимость
     * здесь нельзя — это тихая порча пакета вместо внятного отказа.
     */
    const val VERSION: Int = 3

    /** Тип сообщения C2S: объявление своего набора провайдеров. */
    const val MSG_ANNOUNCE: Int = 1

    /** Тип сообщения C2S: заливка части картинки `file`-провайдера. */
    const val MSG_UPLOAD: Int = 2

    /** Тип сообщения C2S: запрос части картинки (чужой `file`-провайдер). */
    const val MSG_FETCH: Int = 3

    /** Тип сообщения S2C: снимок роустера. */
    const val MSG_ROSTER: Int = 4

    /** Тип сообщения S2C: часть картинки в ответ на [MSG_FETCH]. */
    const val MSG_CHUNK: Int = 5

    /** Канал клиент→сервер (Fabric custom payload id). */
    const val REQUEST_CHANNEL: String = "capecraft:sync_req"

    /** Канал сервер→клиент. */
    const val RESPONSE_CHANNEL: String = "capecraft:sync_resp"

    /**
     * Разобрать id канала на `namespace` и `path`.
     *
     * Нужно, потому что API версий трактуют строку канала по-разному:
     * yarn `CustomPayload.id("ns:path")` ждёт полный id, а Mojang
     * `CustomPacketPayload.createType(...)` в 26.2 вызывает
     * `Identifier.withDefaultNamespace(...)`, который НЕ проверяет наличие
     * неймспейса — он безусловно подставляет `minecraft` и берёт всю строку
     * как path. С `capecraft:sync_req` это даёт path с двоеточием и
     * `IdentifierException` на старте мода (поймано запуском сервера 26.2).
     *
     * Поэтому версионная обвязка не «переинтерпретирует» константу, а
     * зовёт этот разбор и собирает `Identifier`/`Id` из готовых частей —
     * так id канала совпадает на всех версиях.
     */
    fun channelParts(channel: String): Pair<String, String> {
        val colon = channel.indexOf(':')
        require(colon > 0 && colon == channel.lastIndexOf(':') && colon < channel.length - 1) {
            "id канала должен быть ровно namespace:path с непустыми частями, а не «$channel»"
        }
        return channel.substring(0, colon) to channel.substring(colon + 1)
    }

    /** Namespace части канала (например `capecraft`). */
    fun channelNamespace(channel: String): String = channelParts(channel).first

    /** Path части канала (например `sync_req`). */
    fun channelPath(channel: String): String = channelParts(channel).second

    /** Максимальная длина одного строкового поля в байтах UTF-8. */
    const val MAX_STRING_BYTES: Int = 1024

    /** Максимальная длина имени провайдера в байтах UTF-8. */
    const val MAX_NAME_BYTES: Int = 128

    /** Максимальный разумный интервал опроса (тиков): 1 час. */
    const val MAX_INTERVAL_TICKS: Int = 72_000

    /** Минимальный интервал опроса (тиков): 1 раз в секунду. */
    const val MIN_INTERVAL_TICKS: Int = 20

    /** Минимальный таймаут ответа (тиков). */
    const val MIN_TIMEOUT_TICKS: Int = 20

    /** Интервал опроса по умолчанию: 40 тиков = 2 секунды. */
    const val DEFAULT_INTERVAL_TICKS: Int = 40

    /** Таймаут ответа по умолчанию: 100 тиков = 5 секунд. */
    const val DEFAULT_TIMEOUT_TICKS: Int = 100

    /**
     * Потолок адаптивного интервала: 1200 тиков = 60 секунд.
     *
     * Больше замедляться незачем: смена плаща — событие редкое (владелец
     * меняет его несколько раз в день), а 60 секунд — цена, которую
     * пользователь ещё не замечает на своём плаще.
     */
    const val MAX_BACKOFF_INTERVAL_TICKS: Int = 1200

    /**
     * Через сколько тиков молчания докачка считается зависшей и начинается заново.
     *
     * Считается от интервала ожидания, а не от константы: между двумя кусками
     * клиент ждёт [waitTicks], и если таймаут короче этого ожидания, то
     * нормальная медленная передача выглядит зависшей — недособранное
     * выбрасывается, запрос уходит с нуля, и картинка больше одного чанка не
     * собирается никогда. Держим два интервала ожидания плюс запас.
     */
    fun stallTicks(waitTicks: Int): Int = waitTicks * 2 + MIN_INTERVAL_TICKS

    /**
     * Столько ответов подряд «без изменений» нужно, чтобы начать замедляться.
     *
     * Первые ответы идут с базовым интервалом: смена экипировки обычно
     * происходит в первые секунды после входа (мод раздаёт комплект, игрок
     * переодевает кап), и ловить её надо быстро.
     */
    const val STABLE_RESPONSES_BEFORE_BACKOFF: Int = 3

    /**
     * Разброс интервала в процентах, чтобы клиенты не били по серверу
     * синхронно («стад-herd» после рестарта/рестарта лобби: у всех игроков
     * таймер стартует в один тик, и без разброса они бьют запросами в одни
     * и те же тики). Реализация детерминированная — см. [CapeSyncState].
     */
    const val BACKOFF_JITTER_PERCENT: Int = 20

    // ───────────────────────── лимиты v2 ─────────────────────────

    /**
     * Максимум провайдеров в объявлении одного игрока.
     *
     * В v1 это был лимит на «сколько провайдеров вообще можно носить» и он
     * упирался в [MAX_PAYLOAD_BYTES]. Теперь [MAX_PAYLOAD_BYTES] ограничивает
     * только Control-сообщения (announce/fetch), а не снимок роустера, так
     * что лимит отдельный и заметно меньше: 64 провайдера на игрока в роустере
     * размножаются на каждого зрителя.
     */
    const val MAX_PROVIDERS: Int = 32

    /** Максимум игроков в одном снимке роустера. */
    const val MAX_ROSTER_PLAYERS: Int = 128

    /**
     * Потолок одного снимка роустера.
     *
     * Худший случай честно не влезает ни в какой разумный потолок: 128 игроков ×
     * 32 провайдера × (до 1024 байт в `primary` и столько же в `extract`) — это
     * мегабайты. Поэтому сервер собирает снимок **до** упора в этот потолок,
     * кладёт более старых игроков в хвост, а не попадающий — отбрасывает с
     * флагом `truncated`. Клиент по флагу знает, что список неполный, и не
     * считает отсутствие игрока признаком, что у него нет плаща.
     *
     * Реалистичный случай (5 провайдеров на игрока, короткие URL) — около
     * 150 КиБ на 128 игроков, то есть потолок не жмёт.
     */
    const val MAX_ROSTER_BYTES: Int = 512 * 1024

    /** Потолок Control-сообщения (announce/fetch/chunk без картинки). */
    const val MAX_PAYLOAD_BYTES: Int = 128 * 1024

    /** Максимум предикатов в одном `when` или в одном `if`. */
    const val MAX_PREDICATES: Int = 16

    /**
     * Максимальная длина имени поля в предикате (байты UTF-8).
     *
     * Для `if` это же ограничение держит имя переменной: аддонное имя
     * вида `myAddon.someLongField` укладывается с запасом, а произвольно
     * длинная строка в проводе не нужна ни одному реальному случаю.
     */
    const val MAX_FIELD_BYTES: Int = 64

    /** Максимальная длина строкового ожидаемого значения (байты UTF-8). */
    const val MAX_EXPECTED_STR_BYTES: Int = 128

    /**
     * Потолок одной картинки, [MAX_IMAGE_BYTES].
     *
     * Ограничен сверху, потому что картинку присылает клиент, а сервер её
     * перекладывает в памяти и в кэше. 8 МиБ — заведомо больше любого разумного
     * Stacked PNG (13 кадров 256×128 весят сотни КиБ) и заведомо меньше
     * «прислать 8 МиБ на каждого из 128 игроков».
     */
    const val MAX_IMAGE_BYTES: Int = 8 * 1024 * 1024

    /** Суммарный потолок картинок от одного игрока. */
    const val MAX_TOTAL_IMAGE_BYTES: Int = 16 * 1024 * 1024

    /** Максимум кусков, в которых едет одна картинка. */
    const val MAX_CHUNKS_PER_IMAGE: Int = 256

    /**
     * Размер куска при передаче картинки, [CHUNK_BYTES].
     *
     * 64 КиБ: заметно меньше [MAX_PAYLOAD_BYTES] (128 КиБ), поэтому чанк
     * всегда влезает в пакет целиком и не зависит от фрагментации на уровне
     * netty, и при этом достаточно крупный, чтобы стэнч на 13 кадров — это
     * единицы пакетов, а не сотни.
     */
    const val CHUNK_BYTES: Int = 64 * 1024

    /** Длина хэша картинки в байтах: sha-256. */
    const val IMAGE_HASH_BYTES: Int = 32

    /**
     * Сколько роустеров держим на сервере до вытеснения.
     *
     * Ровно [MAX_ROSTER_PLAYERS]: сервер рассылает снимок целиком, поэтому
     * держать больше бессмысленно — вытесненного игрока всё равно не видно
     * ни в одном снимке.
     */
    const val ROSTER_HISTORY: Int = MAX_ROSTER_PLAYERS

    /**
     * Потолок id объекта в роустере (байты UTF-8).
     *
     * Имён тут больше нет — только непрозрачный идентификатор, который клиенту
     * предъявляет сам отправитель, а сервер проверяет. Держим с запасом под
     * uuid с дефисами (36) и возможный будущий формат покороче, но не на
     * «имя игрока» — потому что имена меняются, а идентификатор обязан быть
     * устойчивым, иначе плащ отвяжется от того, кто его рисует.
     */
    const val MAX_OBJECT_ID_BYTES: Int = 36
}

/** Нарушение протокола: битый/чужой payload, превышены лимиты, несовместимая версия. */
class SyncProtocolException(message: String) : Exception(message)
