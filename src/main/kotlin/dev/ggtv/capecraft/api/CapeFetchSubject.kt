package dev.ggtv.capecraft.api

/**
 * Чей плащ сейчас запрашивается.
 *
 * Аддон-провайдер (`type = "seed"` и подобные) вызывается на каждый
 * наблюдаемый объект, но [dev.ggtv.capecraft.api.provider.CapeValues] собирается
 * один раз при чтении конфига и игрока не содержит. Без него аддон физически не
 * может отличить «плащ владельца» от «плащ соседа» и обязан нарисовать всем
 * одно и то же — либо гадать, взяв локального игрока.
 *
 * [uuid] приходит без дефисов, как в плейсхолдере `{uuid}`: аддон, который
 * считает палитру по хэшу идентичности, обязан получить ровно ту же строку, что
 * и `{uuid}` в URL, иначе у владельца и у наблюдателя получатся разные картинки
 * для одного и того же плаща.
 *
 * Значение нужно читать из [CapeApiHolder.subject] — оно выставляется модом на
 * время вызова аддона и недоступно вне этого вызова.
 */
data class CapeFetchSubject(
    /** UUID без дефисов. */
    val uuid: String,
    /** Ник наблюдаемого игрока; может быть пустым, если ещё не известен. */
    val username: String,
    /** Имя провайдера, который отдал картинку (для логов и отладки). */
    val providerName: String,
)